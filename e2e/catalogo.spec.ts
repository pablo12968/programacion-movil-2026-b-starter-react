import { expect, test } from '@playwright/test';
import { mkdirSync } from 'node:fs';

test('CRUD real, filtros, validación y confirmación', async ({ page }, testInfo) => {
  const name = `Producto prueba ${testInfo.project.name}`;
  const evidencePath = `docs/evidencias/${testInfo.project.name}`;
  mkdirSync(evidencePath, { recursive: true });
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/productos');
  const active = page.locator('.ion-page:not(.ion-page-hidden)');
  await expect(active.getByRole('heading', { name: 'Todos los productos', exact: true })).toBeVisible();
  await expect(active.locator('.product-card')).toHaveCount(8);
  await page.screenshot({ path: `${evidencePath}/01-lista.png`, fullPage: true });
  await active.getByRole('button', { name: 'Bebidas', exact: true }).click();
  await expect(active.locator('.product-card')).toHaveCount(3);
  await active.getByRole('textbox', { name: 'Buscar productos' }).fill('NO EXISTE');
  await expect(active.getByRole('heading', { name: 'Sin resultados' })).toBeVisible();
  await active.getByRole('button', { name: 'Limpiar filtros' }).click();
  await expect(active.locator('.product-card')).toHaveCount(8);
  await active.getByRole('button', { name: 'Nuevo producto' }).click();
  await active.getByRole('button', { name: 'Crear producto', exact: true }).click();
  await expect(active.getByText('Escribe un nombre.', { exact: true })).toBeVisible();
  await expect(active.getByText('El stock debe ser un entero mayor o igual que 0.', { exact: true })).toBeVisible();
  await page.screenshot({ path: `${evidencePath}/02-validacion.png`, fullPage: true });
  await active.getByRole('textbox', { name: 'Nombre', exact: true }).fill(name);
  await active.getByRole('spinbutton', { name: 'Precio (COP)' }).fill('1250000');
  await active.getByRole('spinbutton', { name: 'Stock (unidades)' }).fill('4');
  await active.getByRole('button', { name: 'Hogar', exact: true }).click();
  await active.getByRole('button', { name: 'Crear producto', exact: true }).click();
  await expect(active.getByRole('heading', { name, exact: true })).toBeVisible();
  await expect(active.getByText('$ 1.250.000', { exact: true })).toBeVisible();
  await expect(active.getByText('Pocas unidades', { exact: true })).toBeVisible();
  await page.screenshot({ path: `${evidencePath}/03-detalle.png`, fullPage: true });
  await active.getByRole('button', { name: 'Editar', exact: true }).click();
  await expect(active.getByRole('textbox', { name: 'Nombre', exact: true })).toHaveValue(name);
  await active.getByRole('spinbutton', { name: 'Stock (unidades)' }).fill('0');
  await active.getByRole('button', { name: 'Guardar cambios' }).click();
  await expect(active.getByText('Agotado', { exact: true })).toBeVisible();
  await active.getByRole('button', { name: 'Eliminar', exact: true }).click();
  await expect(active.getByRole('heading', { name: '¿Eliminar este producto?' })).toBeVisible();
  await active.getByRole('button', { name: 'Cancelar', exact: true }).click();
  await expect(active.getByRole('heading', { name, exact: true })).toBeVisible();
  await active.getByRole('button', { name: 'Eliminar', exact: true }).click();
  await active.getByRole('button', { name: 'Confirmar eliminación', exact: true }).click();
  await expect(active.locator('.product-card')).toHaveCount(8);
  await expect(active.getByText(name, { exact: true })).toHaveCount(0);
  expect(errors).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});

test('vacío, error, reintento, carga y 404', async ({ page }, testInfo) => {
  const active = page.locator('.ion-page:not(.ion-page-hidden)');
  await page.route('**/api/products', (route) => route.fulfill({ json: [] }));
  await page.goto('/productos');
  await expect(active.getByRole('heading', { name: 'Tu inventario está vacío' })).toBeVisible();
  await page.unroute('**/api/products');
  await page.route('**/api/products', (route) => route.abort());
  await page.reload();
  await expect(active.getByRole('heading', { name: 'No se pudo cargar' })).toBeVisible();
  await page.screenshot({ path: `docs/evidencias/${testInfo.project.name}/04-error.png`, fullPage: true });
  await page.unroute('**/api/products');
  let release: () => void = () => {};
  const gate = new Promise<void>((resolve) => { release = resolve; });
  await page.route('**/api/products', async (route) => { await gate; await route.continue(); });
  await active.getByRole('button', { name: 'Reintentar' }).click();
  await expect(active.getByText('Cargando productos…', { exact: true })).toBeVisible();
  release();
  await expect(active.locator('.product-card')).toHaveCount(8);
  await page.goto('/productos/999999');
  await expect(active.getByText('No encontramos ese producto.', { exact: true })).toBeVisible();
});

test('rechazo del servidor conserva valores y muestra details', async ({ page }) => {
  await page.goto('/productos/nuevo');
  const active = page.locator('.ion-page:not(.ion-page-hidden)');
  await active.getByRole('textbox', { name: 'Nombre', exact: true }).fill('Café prueba');
  await active.getByRole('spinbutton', { name: 'Precio (COP)' }).fill('8500');
  await active.getByRole('spinbutton', { name: 'Stock (unidades)' }).fill('5');
  await active.getByRole('button', { name: 'Bebidas', exact: true }).click();
  await page.route('**/api/products', (route) => route.fulfill({ status: 400, json: { error: 'Datos inválidos', details: ['Mensaje del servidor de prueba'] } }));
  await active.getByRole('button', { name: 'Crear producto', exact: true }).click();
  await expect(active.getByText('Mensaje del servidor de prueba', { exact: true })).toBeVisible();
  await expect(active.getByRole('textbox', { name: 'Nombre', exact: true })).toHaveValue('Café prueba');
});
